export function t(lang: 'en' | 'hi', key: string) {
  const keys = key.split('.');
  let result: any = translations[lang];
  for (const k of keys) {
    if (result && result[k]) {
      result = result[k];
    } else {
      return key;
    }
  }
  return result;
}
